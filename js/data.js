// Если в браузере сохранен один из примеров старой версии — дописываем недостающие значения из него
// (только пустые клетки; то, что вписано вручную, и выводы не трогаем)
function fillFromExample(s){
  const ex=EXAMPLES.find(e=>e.company===s.company); if (!ex) return s;
  for (const [code,arr] of Object.entries(ex.values)){
    s.years.forEach((y,i)=>{
      const k=ex.years.indexOf(y); if (k<0 || arr[k]==null) return;
      if (!s.values[code]) s.values[code]=Array(s.years.length).fill(null);
      if (s.values[code][i]==null) s.values[code][i]=arr[k];
    });
  }
  return s;
}
