/* Расчеты коэффициентов с подстановкой — в оформлении как в образце:
     Коэффициент абсолютной ликвидности Кал=(ДС+КФВ)/КО:
     К₂₀₂₅ = (21861286 + 888764) / 209341672 = 0,11 (ниже рекомендуемого интервала 0,15–0,2);
   В Word эти строки стоят прямо перед таблицами 2.8, 2.9 и 2.10 (как в образце),
   на странице — все вместе в разделе «Расчеты». */

// Обозначение (индекс у «К»), формула и слагаемые числителя/знаменателя из base().
// Если слагаемых несколько, при подстановке они берутся в скобки.
const FORMULAS={
  'абсолютной ликвидности':             {sym:'ал',     expr:'(ДС+КФВ)/КО',      num:b=>[b.DS,b.KFV],           den:b=>[b.KO]},
  'срочной ликвидности':                {sym:'ср.л',   expr:'(ДС+КФВ+ДЗ)/КО',   num:b=>[b.DS,b.KFV,b.DZ],      den:b=>[b.KO]},
  'ликвидности при мобилизации средств':{sym:'лмс',    expr:'(З+НДС)/КО',       num:b=>[b.Z,b.NDS],            den:b=>[b.KO]},
  'общей ликвидности':                  {sym:'ол',     expr:'(ДС+КФВ+ДЗ+З)/КО', num:b=>[b.DS,b.KFV,b.DZ,b.Z],  den:b=>[b.KO]},
  'финансовой независимости':           {sym:'ф.н.',   expr:'СК/ВБ',            num:b=>[b.SK],                 den:b=>[b.VB]},
  'финансовой напряженности':           {sym:'ф.напр.',expr:'ЗК/ВБ',            num:b=>[b.DO,b.KO],            den:b=>[b.VB]},
  'самофинансирования':                 {sym:'ф.с.',   expr:'СК/ЗК',            num:b=>[b.SK],                 den:b=>[b.DO,b.KO]},
  'задолженности':                      {sym:'з',      expr:'ЗК/СК',            num:b=>[b.DO,b.KO],            den:b=>[b.SK]},
  'обеспеченности собственными оборотными средствами':{sym:'о',  expr:'СОК/ОА',     num:b=>[b.SOK],    den:b=>[b.OA]},
  'маневренности собственных оборотных средств':      {sym:'м',  expr:'СОК/СК',     num:b=>[b.SOK],    den:b=>[b.SK]},
  'соотношения мобильных и иммобилизованных активов': {sym:'с',  expr:'ОА/ВОА',     num:b=>[b.OA],     den:b=>[b.VOA]},
  'имущества производственного назначения':           {sym:'ипн',expr:'(ВОА+З)/ВБ', num:b=>[b.VOA,b.Z],den:b=>[b.VB]},
};
const LEGEND='ДС — денежные средства и денежные эквиваленты (стр. 1250); КФВ — краткосрочные финансовые вложения (стр. 1240); '+
  'ДЗ — дебиторская задолженность (стр. 1230); З — запасы (стр. 1210); НДС — НДС по приобретенным ценностям (стр. 1220); '+
  'ОА — оборотные активы (стр. 1200); ВОА — внеоборотные активы (стр. 1100); ВБ — валюта баланса (стр. 1600); '+
  'СК — собственный капитал (стр. 1300); ЗК — заемный капитал (стр. 1400 + стр. 1500); КО — краткосрочные обязательства (стр. 1500); '+
  'СОК — собственный оборотный капитал (СК − ВОА); ДКЗ — долгосрочные кредиты и займы (стр. 1410); ККЗ — краткосрочные кредиты и займы (стр. 1510).';

// Подстановка чисел как в образце: без пробелов между разрядами, слагаемые через « + »
const sn = x => fx(x,0);
function joinTerms(xs, op='+'){ return xs.map((x,k)=> k===0 ? sn(x) : ` ${op} `+sn(x)).join(''); }
const grp = xs => xs.length>1 ? `(${joinTerms(xs)})` : sn(xs[0]);

// runs: [{t:'текст'}, {t:'2025', sub:true}] — в Word получается подстрочный индекс
const R = (t,sub)=>({t,sub:!!sub});
const end = (k,n) => k===n-1 ? '.' : ';';

// part: 'liq' — к таблице 2.8, 'fin' — к 2.9, 'abs' — к 2.10. Возвращает абзацы [{f:runs, keep}]
function calcBlocks(part){
  const I=state.years.map((_,i)=>i).filter(i=>has('bal',i)), B=[];
  if (!I.length) return B;
  if (part==='liq' || part==='fin'){
    for (const [name,norm,fn,d] of (part==='liq'?LIQ:FIN)){
      const F=FORMULAS[name];
      B.push({f:[R(`Коэффициент ${name} К`),R(F.sym,true),R(`=${F.expr}:`)], keep:true});
      I.forEach((i,k)=>{
        const b=base(i), x=fn(b);
        if (x==null){ B.push({f:[R('К'),R(Y(i),true),R(' — не рассчитывается (знаменатель равен нулю)'+end(k,I.length))]}); return; }
        const chk=normCheck(x,norm,d);
        B.push({f:[R('К'),R(Y(i),true),R(` = ${grp(F.num(b))} / ${grp(F.den(b))} = ${fx(x,d)}${chk?` (${chk.text})`:''}${end(k,I.length)}`)]});
      });
    }
  } else {
    const AUX=[
      ['Наличие собственного оборотного капитала','СОК','СК - ВОА',  b=>[b.SK,b.VOA], '-', b=>b.SOK],
      ['Наличие собственных и долгосрочных заемных источников формирования запасов','СДИ','СОК + ДКЗ', b=>[b.SOK,b.DKZ], '+', b=>b.SDI],
      ['Общая величина основных источников формирования запасов','ОИ','СДИ + ККЗ', b=>[b.SDI,b.KKZ], '+', b=>b.OI],
    ];
    for (const [name,sym,expr,terms,op,res] of AUX){
      B.push({f:[R(`${name} ${sym} = ${expr}:`)], keep:true});
      I.forEach((i,k)=>{ const b=base(i); B.push({f:[R(sym),R(Y(i),true),R(` = ${joinTerms(terms(b),op)} = ${sn(res(b))}${end(k,I.length)}`)]}); });
    }
    B.push({f:[R('На основе вышеуказанных трех вспомогательных показателей определим абсолютные показатели финансовой устойчивости. Для этого необходимо из величины вспомогательных показателей вычесть величину запасов.')]});
    I.forEach((i,k)=>{ const b=base(i);
      [['ΔСОК',b.SOK,b.dSOK],['ΔСДИ',b.SDI,b.dSDI],['ΔОИ',b.OI,b.dOI]].forEach(([s,a,r],j)=>
        B.push({f:[R(s),R(Y(i),true),R(` = ${sn(a)} - ${sn(b.Z)} = ${sn(r)}${j===2?end(k,I.length):';'}`)]}));
    });
    B.push({f:[R('Трехмерная модель (ΔСОК ≥ 0; ΔСДИ ≥ 0; ΔОИ ≥ 0 → 1, иначе 0):')], keep:true});
    I.forEach((i,k)=>{ const t=stabType(base(i)); B.push({f:[R(`на 31.12.${Y(i)} — ${t.m}, ${t.t.toLowerCase()}${end(k,I.length)}`)]}); });
  }
  return B;
}

/* ---- Страница: раздел «Расчеты» целиком ---- */
function calcHTML(){
  const runs = rs => rs.map(r=> r.sub ? `<sub>${esc(r.t)}</sub>` : esc(r.t)).join('');
  const part = (title,p) => { const B=calcBlocks(p); return B.length ? `<h3>${esc(title)}</h3>`+B.map(b=>`<p class="${b.keep?'':'f'}">${runs(b.f)}</p>`).join('') : ''; };
  const html = part('Коэффициенты ликвидности (к таблице 2.8)','liq') + part('Показатели финансовой устойчивости (к таблице 2.9)','fin') + part('Абсолютные показатели финансовой устойчивости (к таблице 2.10)','abs');
  return html ? `<p class="legend">Условные обозначения: ${esc(LEGEND)}</p>`+html : '<p>Нет данных баланса для расчетов.</p>';
}

/* ---- Word: абзацы расчетов перед таблицей (14 пт, интервал 1,5, отступ 1,25 см — как текст образца) ---- */
function calcXml(part){ return calcBlocks(part).map(b=>wParaRuns(b.f,{keep:b.keep})).join(''); }
