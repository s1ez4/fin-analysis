/* Раздел «Расчеты»: формулы с подстановкой чисел для каждого коэффициента и года.
   Пример строки: К₂₀₂₅ = 276 493 513 / 615 400 445 = 0,45 (ниже рекомендуемого значения 0,5).
   Блоки раздела — общие для страницы (HTML) и для Word (runs с подстрочными индексами). */

// Формулы коэффициентов: обозначение (индекс у «К»), формула словами, числитель и знаменатель из base().
// Числитель/знаменатель — списки слагаемых; если слагаемых несколько, они берутся в скобки.
const FORMULAS={
  'абсолютной ликвидности':            {sym:'абл',   expr:'(ДС + КФВ) / КО',      num:b=>[b.DS,b.KFV],           den:b=>[b.KO]},
  'срочной ликвидности':               {sym:'сл',    expr:'(ДС + КФВ + ДЗ) / КО', num:b=>[b.DS,b.KFV,b.DZ],      den:b=>[b.KO]},
  'ликвидности при мобилизации средств':{sym:'лмс',  expr:'(З + НДС) / КО',       num:b=>[b.Z,b.NDS],            den:b=>[b.KO]},
  'общей ликвидности':                 {sym:'ол',    expr:'(ДС + КФВ + ДЗ + З) / КО', num:b=>[b.DS,b.KFV,b.DZ,b.Z], den:b=>[b.KO]},
  'финансовой независимости':          {sym:'фн',    expr:'СК / ВБ',              num:b=>[b.SK],                 den:b=>[b.VB]},
  'финансовой напряженности':          {sym:'фнапр', expr:'ЗК / ВБ = (ДО + КО) / ВБ', num:b=>[b.DO,b.KO],        den:b=>[b.VB]},
  'самофинансирования':                {sym:'сф',    expr:'СК / ЗК = СК / (ДО + КО)', num:b=>[b.SK],             den:b=>[b.DO,b.KO]},
  'задолженности':                     {sym:'з',     expr:'ЗК / СК = (ДО + КО) / СК', num:b=>[b.DO,b.KO],        den:b=>[b.SK]},
  'обеспеченности собственными оборотными средствами':{sym:'осс', expr:'СОК / ОА', num:b=>[b.SOK],             den:b=>[b.OA]},
  'маневренности собственных оборотных средств':      {sym:'м',   expr:'СОК / СК', num:b=>[b.SOK],             den:b=>[b.SK]},
  'соотношения мобильных и иммобилизованных активов': {sym:'м/и', expr:'ОА / ВОА', num:b=>[b.OA],              den:b=>[b.VOA]},
  'имущества производственного назначения':           {sym:'пим', expr:'(ВОА + З) / ВБ', num:b=>[b.VOA,b.Z],   den:b=>[b.VB]},
};
const LEGEND='ДС — денежные средства и денежные эквиваленты (стр. 1250); КФВ — финансовые вложения, за исключением денежных эквивалентов (стр. 1240); '+
  'ДЗ — дебиторская задолженность (стр. 1230); З — запасы (стр. 1210); НДС — НДС по приобретенным ценностям (стр. 1220); '+
  'ОА — оборотные активы (стр. 1200); ВОА — внеоборотные активы (стр. 1100); ВБ — валюта баланса (стр. 1600); '+
  'СК — собственный капитал (стр. 1300); ДО — долгосрочные обязательства (стр. 1400); КО — краткосрочные обязательства (стр. 1500); '+
  'ЗК — заемный капитал (ДО + КО); СОК — собственный оборотный капитал (СК − ВОА); '+
  'ДКЗ — долгосрочные кредиты и займы (стр. 1410); ККЗ — краткосрочные кредиты и займы (стр. 1510).';

// Подстановка: первое число как есть, следующие — со своим знаком операции; отрицательные в скобках
const sn = x => fmtNum(Math.round(x),0);
function joinTerms(xs, op='+'){
  return xs.map((x,k)=> k===0 ? sn(x) : ` ${op} `+(x<0?`(${sn(x)})`:sn(x))).join('');
}
const grp = xs => xs.length>1 ? `(${joinTerms(xs)})` : (xs[0]<0?`(${sn(xs[0])})`:sn(xs[0]));

// runs: [{t:'текст'}, {t:'2025', sub:true}] — так в Word получается подстрочный индекс
const R = (t,sub)=>({t,sub:!!sub});

function calcBlocks(){
  const I=state.years.map((_,i)=>i).filter(i=>has('bal',i));
  const B=[];
  B.push({h:'Расчеты'});
  if (!I.length){ B.push({p:[R('Нет данных баланса для расчетов.')]}); return B; }
  B.push({p:[R('Условные обозначения: '+LEGEND)]});

  // коэффициенты ликвидности и финансовой устойчивости
  const ratioPart=(title, defs)=>{
    B.push({h2:title});
    for (const [name,norm,fn,d] of defs){
      const F=FORMULAS[name]; if(!F) continue;
      B.push({p:[R(`Коэффициент ${name}: К`),R(F.sym,true),R(` = ${F.expr}${norm==='индивидуально'?' (норматив устанавливается индивидуально)':`, рекомендуемое значение ${norm}`}.`)], keep:true});
      I.forEach((i,k)=>{
        const b=base(i), x=fn(b);
        if (x==null){ B.push({f:[R('К'),R(Y(i),true),R(' — нет данных (знаменатель равен нулю);')]}); return; }
        const chk=normCheck(x,norm,d);
        B.push({f:[R('К'),R(Y(i),true),R(` = ${grp(F.num(b))} / ${grp(F.den(b))} = ${fmtNum(x,d)}${chk?` (${chk.text})`:''}${k===I.length-1?'.':';'}`)]});
      });
    }
  };
  ratioPart('Расчет коэффициентов ликвидности (к таблице 2.8)', LIQ);
  ratioPart('Расчет показателей финансовой устойчивости (к таблице 2.9)', FIN);

  // абсолютные показатели (таблица 2.10), тыс. руб.
  B.push({h2:'Расчет абсолютных показателей финансовой устойчивости (к таблице 2.10), тыс. руб.'});
  const ABS=[
    ['СОК','СК − ВОА',   b=>[b.SK,b.VOA],  '−', b=>b.SOK],
    ['СДИ','СОК + ДКЗ',  b=>[b.SOK,b.DKZ], '+', b=>b.SDI],
    ['ОИ', 'СДИ + ККЗ',  b=>[b.SDI,b.KKZ], '+', b=>b.OI],
    ['ΔСОК','СОК − З',   b=>[b.SOK,b.Z],   '−', b=>b.dSOK],
    ['ΔСДИ','СДИ − З',   b=>[b.SDI,b.Z],   '−', b=>b.dSDI],
    ['ΔОИ', 'ОИ − З',    b=>[b.OI,b.Z],    '−', b=>b.dOI],
  ];
  for (const [sym,expr,terms,op,res] of ABS){
    B.push({p:[R(`${sym} = ${expr}:`)], keep:true});
    I.forEach((i,k)=>{ const b=base(i);
      B.push({f:[R(sym),R(Y(i),true),R(` = ${joinTerms(terms(b),op)} = ${sn(res(b))}${k===I.length-1?'.':';'}`)]}); });
  }
  B.push({p:[R('Трехмерная модель (ΔСОК ≥ 0; ΔСДИ ≥ 0; ΔОИ ≥ 0 → 1, иначе 0):')], keep:true});
  I.forEach((i,k)=>{ const t=stabType(base(i)); B.push({f:[R(`на ${'31.12.'+Y(i)} — ${t.m}, ${t.t.toLowerCase()}${k===I.length-1?'.':';'}`)]}); });
  return B;
}

/* ---- Страница ---- */
function calcHTML(){
  const runs = rs => rs.map(r=> r.sub ? `<sub>${esc(r.t)}</sub>` : esc(r.t)).join('');
  return calcBlocks().map(b=>
    b.h  ? '' :                                   // заголовок раздела уже есть на странице
    b.h2 ? `<h3>${esc(b.h2)}</h3>` :
    b.p  ? `<p>${runs(b.p)}</p>` :
           `<p class="f">${runs(b.f)}</p>`).join('');
}

/* ---- Word ---- */
function calcSectionXml(){
  return calcBlocks().map(b=>
    b.h  ? wPara(b.h,{b:true,jc:'center',ind:false,keep:true,after:240,pb:true}) :
    b.h2 ? wPara(b.h2,{b:true,jc:'left',ind:false,keep:true,after:120}) :
    b.p  ? wParaRuns(b.p,{keep:b.keep, jc:b.keep?'left':'both'}) :   // заголовки формул — без растяжения по ширине
           wParaRuns(b.f,{jc:'left',after:0})).join('');
}
