  if (a!==z) s.push(`За ${yrs(a,z)} ${parts.map(([n,c,gn])=>`${n} ${vh(g(c,a),g(c,z),gn)}`).join(', ')}.`);
  const zk=g('1400',z)+g('1500',z), sk=g('1300',z);
